import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

/*
 * Publishes a recording from dist/examples/atc/demo/ to hashbrown.dev:
 * copies the posters into www/public, points
 * www/src/components/elements/atc-media.ts at content-hashed Vercel Blob
 * URLs, and with `--upload` puts the four videos in the `hashbrown-www-media`
 * store. Each recording gets its own immutable URLs, cached for a year.
 *
 * Uploading needs BLOB_READ_WRITE_TOKEN (the store's token) and VERCEL_TOKEN;
 * without both the Vercel CLI would wait on an interactive login, so the
 * script prints the commands instead.
 */

const REPO = resolve(__dirname, '../../../..');
const OUT = resolve(REPO, 'dist/examples/atc/demo');
const POSTERS = resolve(REPO, 'www/public/image/landing-page');
const MEDIA_MODULE = resolve(REPO, 'www/src/components/elements/atc-media.ts');
/** The public host of the `hashbrown-www-media` Blob store. */
const BLOB_HOST = 'https://ue1aiy83g4k7z6ts.public.blob.vercel-storage.com';

/** The Blob pathname for a file: its name plus the first 12 hex of its SHA-256. */
function hashedPathname(name: string, contents: Buffer): string {
  const hash = createHash('sha256').update(contents).digest('hex').slice(0, 12);
  const dot = name.lastIndexOf('.');

  return `video/${name.slice(0, dot)}-${hash}${name.slice(dot)}`;
}

/** The source of `atc-media.ts` for the given Blob pathnames. */
function mediaModule(paths: {
  readonly demo: { readonly webm: string; readonly mp4: string };
  readonly loop: { readonly webm: string; readonly mp4: string };
}): string {
  const url = (path: string) => `'${BLOB_HOST}/${path}'`;

  return `// Generated by examples/atc/e2e/demo/publish.ts; re-run it after a new recording.

/** A video's WebM and MP4 copies on Vercel Blob, and its poster in /public. */
export interface AtcVideo {
  readonly webm: string;
  readonly mp4: string;
  readonly poster: string;
  readonly width: number;
  readonly height: number;
}

/** The atc demo: about 45 s of code and app, for the blog and docs. */
export const ATC_DEMO_VIDEO: AtcVideo = {
  webm: ${url(paths.demo.webm)},
  mp4: ${url(paths.demo.mp4)},
  poster: '/image/landing-page/atc-demo-poster.webp',
  width: 1440,
  height: 810,
};

/** The home page loop: the app answering one question, seamless. */
export const ATC_LOOP_VIDEO: AtcVideo = {
  webm: ${url(paths.loop.webm)},
  mp4: ${url(paths.loop.mp4)},
  poster: '/image/landing-page/atc-loop-poster.webp',
  width: 1440,
  height: 900,
};
`;
}

function main(): void {
  const files = [
    'atc-demo.webm',
    'atc-demo.mp4',
    'atc-loop.webm',
    'atc-loop.mp4',
  ];
  const paths = Object.fromEntries(
    files.map((name) => [
      name,
      hashedPathname(name, readFileSync(join(OUT, name))),
    ]),
  );
  for (const poster of ['atc-demo-poster.webp', 'atc-loop-poster.webp']) {
    copyFileSync(join(OUT, poster), join(POSTERS, poster));
  }
  writeFileSync(
    MEDIA_MODULE,
    mediaModule({
      demo: { webm: paths['atc-demo.webm'], mp4: paths['atc-demo.mp4'] },
      loop: { webm: paths['atc-loop.webm'], mp4: paths['atc-loop.mp4'] },
    }),
  );
  console.log(`Wrote ${MEDIA_MODULE} and the posters.`);
  const blob = process.env['BLOB_READ_WRITE_TOKEN'];
  const vercel = process.env['VERCEL_TOKEN'];
  const upload = process.argv.includes('--upload');
  for (const name of files) {
    const args = [
      'blob',
      'put',
      join(OUT, name),
      '--access',
      'public',
      '--pathname',
      paths[name],
      '--cache-control-max-age',
      '31536000',
    ];
    if (upload && blob && vercel) {
      execFileSync(
        join(REPO, 'node_modules/.bin/vercel'),
        [...args, '--rw-token', blob, '--token', vercel],
        { cwd: REPO, stdio: ['ignore', 'inherit', 'inherit'] },
      );
    } else {
      console.log(
        `npx vercel ${args.join(' ')} --rw-token "$BLOB_READ_WRITE_TOKEN" --token "$VERCEL_TOKEN"`,
      );
    }
  }
  if (!upload || !blob || !vercel) {
    console.log(
      'Not uploaded. Run the commands above, or re-run with --upload and both tokens set.',
    );
  }
}

main();
