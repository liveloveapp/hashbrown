import { join } from 'node:path';
import { readReferenceInput } from './dotnet-reference-input.mjs';
import { repoRoot } from './repo-root';

/** Authored XML prose and exact cross-reference identities from the compiled SDK. */
export interface DotnetDocs {
  summary: string;
  remarks: string;
  returns: string;
  params: { name: string; description: string }[];
  typeParams: { name: string; description: string }[];
  references: { target: string; text: string }[];
}

/** One authored public C# member, with an overload-specific XML identity. */
export interface DotnetMember {
  id: string;
  name: string;
  anchor: string;
  declaration: string;
  docs: DotnetDocs;
}

/** One reviewed exported SDK type and its authored public members. */
export interface DotnetType {
  id: string;
  name: string;
  slug: string;
  declaration: string;
  docs: DotnetDocs;
  members: DotnetMember[];
}

/** Deterministic reference input generated by the SDK-only API tool. */
export interface DotnetReference {
  schemaVersion: 1;
  package: {
    id: 'Hashbrown.AspNetCore';
    version: string;
    status: 'unreleased';
  };
  types: DotnetType[];
}

/** Read and validate committed C# documentation; website builds require no .NET process. */
export function readDotnetReference(
  file = join(repoRoot(), 'packages/dotnet/api/reference-docs.json'),
): DotnetReference {
  return readReferenceInput(file);
}

/** List the C# type pages independently of the TypeScript API Extractor report. */
export function listDotnetSymbols(): DotnetType[] {
  return readDotnetReference().types;
}

/** Find an exact validated C# type route, returning undefined for unknown slugs. */
export function readDotnetSymbol(slug: string): DotnetType | undefined {
  return listDotnetSymbols().find((type) => type.slug === slug);
}

/** Resolve only exact documented SDK XML IDs to actual type pages or member anchors. */
export function dotnetReferenceHref(
  xmlId: string,
  reference = readDotnetReference(),
): string | undefined {
  for (const type of reference.types) {
    const url = '/api/dotnet/' + type.slug;
    if (type.id === xmlId) return url;
    const member = type.members.find((candidate) => candidate.id === xmlId);
    if (member) return url + '#' + member.anchor;
  }
  return undefined;
}
