import { s } from '@hashbrownai/core';
import type { WorkbenchPlan } from './workbench';

/** The two lessons that capture actual UI kit configuration. */
export type WorkbenchUiLesson = 'ui-kits' | 'ui-chatbot';
/** The trusted identities preserved in captured UI frames. */
export type WorkbenchUiComponent = 'SummaryCard' | 'StepsCard' | 'PlanReading';
/** Safe normalized metadata, excluding framework implementations. */
export interface WorkbenchUiKitObservation {
  readonly components: readonly {
    readonly name: string;
    readonly description: string;
    readonly fallback: boolean;
  }[];
  readonly serializedSchema: string;
}
/** Actual SDK configuration accepted structurally by either framework. */
export interface WorkbenchUiKitInput {
  readonly registryMap: ReadonlyMap<
    string,
    {
      readonly name: string;
      readonly description: string;
      readonly fallback?: unknown;
    }
  >;
  readonly serializedSchema: string;
}
/** The shared prop shape supplied to both real exposed component APIs. */
export const workbenchUiPlanProps = {
  title: s.string('A concise plan title, 1–120 characters'),
  steps: s.streaming.array(
    'Exactly two concise steps, each 1–200 characters',
    s.string('A clear action'),
  ),
};
/** The shared plan schema used in trusted wrapper response schemas. */
export const workbenchUiPlanSchema = s.object(
  'Component Props',
  workbenchUiPlanProps,
);

/** Returns the lesson's trusted component descriptors without implementations. */
export function getWorkbenchUiComponents(lesson: WorkbenchUiLesson) {
  return [
    {
      name: 'SummaryCard' as const,
      description: 'Propose a two-step plan for explicit user acceptance.',
    },
    lesson === 'ui-kits'
      ? {
          name: 'StepsCard' as const,
          description:
            'Propose the same two-step plan as ordered steps for explicit user acceptance.',
        }
      : {
          name: 'PlanReading' as const,
          description:
            'Read-only model report of the accepted application plan. No acceptance action.',
        },
  ];
}
/** Returns the two fixed demonstration prompts. */
export function getWorkbenchUiPrompts(
  lesson: WorkbenchUiLesson,
): readonly [string, string] {
  return lesson === 'ui-kits'
    ? [
        'Create the two-step demo plan as a SummaryCard.',
        'Keep the first step and show a shorter second step in a StepsCard.',
      ]
    : [
        'Propose a two-step plan for the trusted UI demo.',
        'Read the plan I accepted and show it as a PlanReading.',
      ];
}
/** Server-owned instructions keep rendering separate from application writes. */
export function getWorkbenchUiSystem(lesson: WorkbenchUiLesson): string {
  return (
    'Before every response call readContext exactly once to read the current application revision and accepted plan. Render exactly one allowed component with a short title (1–120 characters) and exactly two concise nonempty steps (1–200 characters each). Do not add fields or children. Return action text without step numbers; the components render numbering. Rendering never changes application state. Only explicit user acceptance applies a proposal. The initial proposal should outline the trusted UI demo as its first step and record that demo as its second step. ' +
    (lesson === 'ui-kits'
      ? 'Use SummaryCard for the first request, then StepsCard for the follow-up. Keep the first step verbatim and shorten the second step.'
      : 'Use SummaryCard to propose the first two-step plan. For the follow-up use PlanReading and copy the actual accepted plan title and both steps verbatim from readContext. PlanReading is a read-only model report and must never offer or claim acceptance.')
  );
}
/** Builds the same wrapper shape generated by the SDK kit for these components. */
export function getWorkbenchUiResponseSchema(lesson: WorkbenchUiLesson) {
  return s.toJsonSchema(
    s.object(
      'Return a JSON object with a single key "ui" that matches the schema below. Use only these components.',
      {
        ui: s.streaming.array(
          'List of elements',
          s.anyOf(
            getWorkbenchUiComponents(lesson).map(({ name, description }) =>
              s.streaming.object(description, {
                [name]: s.streaming.object(`${name} node`, {
                  props: s.node(
                    s.object('Component Props', workbenchUiPlanProps),
                  ),
                }),
              }),
            ),
          ),
        ),
      },
    ),
  );
}
/** Copies only safe metadata from the actual normalized SDK registry. */
export function normalizeWorkbenchUiKit(
  input: WorkbenchUiKitInput,
): WorkbenchUiKitObservation {
  return {
    components: Array.from(
      input.registryMap.values(),
      ({ name, description, fallback }) => ({
        name,
        description,
        fallback: fallback != null,
      }),
    ),
    serializedSchema: input.serializedSchema,
  };
}
function object(value: unknown): Record<string, unknown> | null {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}
function keys(value: Record<string, unknown>, allowed: readonly string[]) {
  return Object.keys(value).every((key) => allowed.includes(key));
}
function node(value: unknown, lesson: WorkbenchUiLesson) {
  const root = object(value);
  if (
    !root ||
    !keys(root, ['ui']) ||
    !Array.isArray(root['ui']) ||
    root['ui'].length !== 1
  )
    return null;
  const component = object(root['ui'][0]);
  if (!component || Object.keys(component).length !== 1) return null;
  const name = Object.keys(component)[0];
  if (!getWorkbenchUiComponents(lesson).some((entry) => entry.name === name))
    return null;
  const body = object(component[name]);
  if (!body || !keys(body, ['props'])) return null;
  const field = object(body['props']);
  return field ? { component: name as WorkbenchUiComponent, field } : null;
}
/** Extracts SDK node values without inventing missing partial fields. */
export function extractWorkbenchUi(value: unknown, lesson: WorkbenchUiLesson) {
  const parsed = node(value, lesson);
  if (!parsed) return null;
  const { field, component } = parsed;
  const wrapped =
    'value' in field || 'partialValue' in field || 'complete' in field;
  const props = wrapped
    ? (object(field['value']) ?? object(field['partialValue']))
    : field;
  if (!props || !keys(props, ['title', 'steps'])) return null;
  return {
    component,
    props: {
      ...(typeof props['title'] === 'string' ? { title: props['title'] } : {}),
      ...(Array.isArray(props['steps']) &&
      props['steps'].every((step) => typeof step === 'string')
        ? { steps: [...props['steps']] as string[] }
        : {}),
    },
    ready: !wrapped || field['complete'] === true,
  };
}
/** Validates original wire JSON strictly before an application action. */
export function decodeWorkbenchUiDocument(
  json: string,
  lesson: WorkbenchUiLesson,
): {
  readonly component: WorkbenchUiComponent;
  readonly props: WorkbenchPlan;
} | null {
  try {
    const parsed = node(JSON.parse(json), lesson);
    if (!parsed || !keys(parsed.field, ['title', 'steps'])) return null;
    const { title, steps } = parsed.field;
    if (
      typeof title !== 'string' ||
      !title.trim() ||
      title.length > 120 ||
      !Array.isArray(steps) ||
      steps.length !== 2 ||
      !steps.every(
        (step) =>
          typeof step === 'string' && !!step.trim() && step.length <= 200,
      )
    )
      return null;
    return { component: parsed.component, props: { title, steps: [...steps] } };
  } catch {
    return null;
  }
}
