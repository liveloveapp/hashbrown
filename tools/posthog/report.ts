/**
 * Weekly snapshot of the repository-managed dashboards as markdown. Only
 * additive daily totals are summed. Funnels, unique counts, breakdowns, and
 * missing, stale or incomplete results render as `Unavailable` with a reason;
 * they are never shown as zero.
 */
import { access, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createPosthogClient, type QueryParams } from './client.ts';
import { fetchAllPages, loadDashboards } from './sync.ts';

const BARS = ['▁', '▂', '▃', '▄', '▅', '▆', '▇', '█'];
const DAY_MS = 86_400_000;

/**
 * A unicode sparkline scaled to the largest value.
 *
 * @param values - Non-negative values.
 * @returns One bar per value, or `—` when there are none.
 */
export function sparkline(values: readonly number[]): string {
  if (values.length === 0) return '—';
  const max = Math.max(...values, 1);
  return values
    .map((value) => BARS[Math.min(7, Math.round((value / max) * 7))])
    .join('');
}

/**
 * The change between two periods, absolute and in percent.
 *
 * @param counts - This period and the one before.
 * @returns e.g. `+20 (+20%)`, `+5 (new)`, or `—` when both are zero.
 */
export function formatDeltaCell({
  thisWeek,
  lastWeek,
}: {
  thisWeek: number;
  lastWeek: number;
}): string {
  const diff = thisWeek - lastWeek;
  const sign = diff >= 0 ? '+' : '';
  if (lastWeek === 0) return diff > 0 ? `${sign}${diff} (new)` : '—';
  const pct = Math.round((diff / lastWeek) * 100);
  return `${sign}${diff} (${pct >= 0 ? '+' : ''}${pct}%)`;
}

/** One metric row. `null` counts mean unavailable, never zero. */
export interface ReportRow {
  metric: string;
  thisWeek: number | null;
  lastWeek: number | null;
  /** Why the counts are unavailable. */
  unavailable?: string;
  /** Four consecutive 7-day totals, oldest first. */
  weeks: readonly number[];
}

/** One dashboard's rows. */
export interface ReportSection {
  name: string;
  rows: ReportRow[];
}

/**
 * Renders the snapshot markdown.
 *
 * @param sections - One section per dashboard.
 * @param date - The UTC report date, `YYYY-MM-DD`.
 * @returns Markdown.
 */
export function renderReport(
  sections: readonly ReportSection[],
  date: string,
): string {
  const lines = [
    `# Website analytics weekly snapshot — ${date}`,
    '',
    '> Generated by `npx nx report posthog`. Counts cover completed UTC days ending yesterday; today’s partial bucket is excluded. The sparkline shows four consecutive 7-day periods.',
    '',
  ];
  for (const section of sections) {
    lines.push(`## ${section.name}`, '');
    lines.push(
      '| Metric | Last 7 complete UTC days | Preceding 7 UTC days | Δ | 4 periods |',
    );
    lines.push('|--------|----------:|----------:|--:|------|');
    for (const row of section.rows) {
      if (row.thisWeek === null || row.lastWeek === null) {
        lines.push(
          `| ${row.metric} | Unavailable: ${row.unavailable ?? 'no complete result'} | — | — | — |`,
        );
        continue;
      }
      lines.push(
        `| ${row.metric} | ${row.thisWeek.toLocaleString('en-US')} | ${row.lastWeek.toLocaleString('en-US')} | ${formatDeltaCell({ thisWeek: row.thisWeek, lastWeek: row.lastWeek })} | ${sparkline(row.weeks)} |`,
      );
    }
    lines.push('');
  }
  lines.push(
    '## Notes',
    '',
    '<!-- HUMAN: three bullets at most. -->',
    '- _Add observations here._',
    '',
  );
  return lines.join('\n');
}

/** An insight as PostHog returns it; only the fields the report reads. */
export interface FetchedInsight {
  id: number;
  name: string;
  query?: unknown;
  result?: unknown;
}

type Json = Record<string, unknown>;

function isRecord(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function trendsSource(query: unknown): Json | undefined {
  if (!isRecord(query)) return undefined;
  if (query['kind'] === 'TrendsQuery') return query;
  const source = query['source'];
  return isRecord(source) ? source : undefined;
}

function hasBreakdown(source: Json): boolean {
  const filter = source['breakdownFilter'];
  if (!isRecord(filter)) return false;
  const many = filter['breakdowns'];
  return (
    Boolean(filter['breakdown']) || (Array.isArray(many) && many.length > 0)
  );
}

/**
 * Report rows for one insight: one row per series of a daily total trend,
 * summed over the 28 completed UTC days before `asOf`.
 *
 * @param insight - The fetched insight with its result.
 * @param asOf - The report time; its UTC day is excluded as partial.
 * @returns Rows, or a single unavailable row with the reason.
 */
export function insightReportRows(
  insight: FetchedInsight,
  asOf = new Date(),
): ReportRow[] {
  const unavailable = (reason: string): ReportRow[] => [
    {
      metric: insight.name,
      thisWeek: null,
      lastWeek: null,
      weeks: [],
      unavailable: reason,
    },
  ];
  const source = trendsSource(insight.query);
  if (source?.['kind'] !== 'TrendsQuery')
    return unavailable(
      'unsupported insight type (funnels need their own reading)',
    );
  if (source['interval'] !== 'day')
    return unavailable('requires daily event totals');
  const series = source['series'];
  if (!Array.isArray(series) || series.length === 0)
    return unavailable('missing series definition');
  if (
    series.some(
      (item) =>
        isRecord(item) &&
        item['math'] !== undefined &&
        item['math'] !== 'total',
    )
  ) {
    return unavailable(
      'unique or non-additive series cannot be summed into weekly counts',
    );
  }
  if (hasBreakdown(source))
    return unavailable(
      'breakdown results may be truncated; inspect the dashboard',
    );

  const results = insight.result;
  if (!Array.isArray(results) || results.length !== series.length)
    return unavailable('missing or incomplete result series');

  const today = Date.UTC(
    asOf.getUTCFullYear(),
    asOf.getUTCMonth(),
    asOf.getUTCDate(),
  );
  if (!Number.isFinite(today)) return unavailable('invalid UTC report date');
  const expectedDays = Array.from({ length: 28 }, (_, index) =>
    new Date(today - (28 - index) * DAY_MS).toISOString().slice(0, 10),
  );

  const rows: ReportRow[] = [];
  for (const [index, item] of results.entries()) {
    if (!isRecord(item))
      return unavailable('missing or incomplete result series');
    const data = item['data'];
    const days = item['days'];
    if (
      !Array.isArray(data) ||
      data.some(
        (value) =>
          typeof value !== 'number' || !Number.isFinite(value) || value < 0,
      )
    ) {
      return unavailable('missing complete numeric results');
    }
    if (!Array.isArray(days) || days.length !== data.length)
      return unavailable('missing or mismatched daily result dates');
    const byDay = new Map<string, number>();
    for (const [position, day] of days.entries()) {
      if (typeof day !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(day))
        return unavailable('invalid or partial daily result dates');
      const timestamp = Date.parse(`${day}T00:00:00Z`);
      if (
        !Number.isFinite(timestamp) ||
        new Date(timestamp).toISOString().slice(0, 10) !== day ||
        timestamp > today ||
        byDay.has(day)
      ) {
        return unavailable('invalid or duplicate daily result dates');
      }
      byDay.set(day, data[position] as number);
    }
    if (expectedDays.some((day) => !byDay.has(day))) {
      return unavailable(
        'missing the complete 28-day UTC window ending yesterday; cached data may be stale',
      );
    }
    const window = expectedDays.map((day) => byDay.get(day) as number);
    const weeks = [0, 1, 2, 3].map((week) =>
      window
        .slice(week * 7, (week + 1) * 7)
        .reduce((sum, value) => sum + value, 0),
    );
    const definition = series[index];
    const named = isRecord(definition)
      ? (definition['custom_name'] ?? definition['name'])
      : undefined;
    const label = named ?? item['label'] ?? `series ${index + 1}`;
    rows.push({
      metric:
        results.length > 1
          ? `${insight.name} — ${String(label)}`
          : insight.name,
      thisWeek: weeks[3],
      lastWeek: weeks[2],
      weeks,
    });
  }
  return rows;
}

/** The read access the report needs; faked in tests. */
export interface ReportClient {
  get(path: string, query?: QueryParams): Promise<unknown>;
}

interface FetchedDashboard {
  id: number;
  name: string;
  tiles?: Array<{ insight?: number | { id?: number } | null }>;
}

async function managedDashboardIds(root: string): Promise<number[]> {
  const dashboards = await loadDashboards(root);
  if (dashboards.length === 0)
    throw new Error('No managed dashboards configured');
  return dashboards.map(({ value }) => {
    if (value.posthog_id === null)
      throw new Error(
        `Dashboard ${value.slug} has not been synced; run sync:apply first`,
      );
    return value.posthog_id;
  });
}

/**
 * Fetches the managed dashboards and their insights and renders the report.
 *
 * @param options.client - Read access to PostHog; defaults to the live client.
 * @param options.asOf - Report time; defaults to now.
 * @param options.dashboardIds - Dashboards to report; defaults to the synced committed ones.
 * @returns The markdown and its UTC date.
 */
export async function generateReport(
  options: {
    client?: ReportClient;
    asOf?: Date;
    dashboardIds?: readonly number[];
  } = {},
): Promise<{ markdown: string; date: string }> {
  const asOf = options.asOf ?? new Date();
  const client = options.client ?? createPosthogClient();
  const ids =
    options.dashboardIds ??
    (await managedDashboardIds(dirname(fileURLToPath(import.meta.url))));
  const listed = await fetchAllPages<FetchedDashboard>(
    async (offset, limit) =>
      (await client.get('/dashboards/', { limit, offset })) as {
        results?: FetchedDashboard[];
        next?: string | null;
      },
  );

  const sections: ReportSection[] = [];
  for (const id of ids) {
    if (!listed.some((dashboard) => dashboard.id === id))
      throw new Error(`Managed dashboard ${id} is absent from PostHog`);
    const dashboard = (await client.get(
      `/dashboards/${id}/`,
    )) as FetchedDashboard;
    if (!Array.isArray(dashboard.tiles))
      throw new Error(`Dashboard ${id} response is missing tiles`);
    const rows: ReportRow[] = [];
    for (const tile of dashboard.tiles) {
      const insightId =
        typeof tile.insight === 'number' ? tile.insight : tile.insight?.id;
      if (typeof insightId !== 'number') continue;
      const insight = (await client.get(`/insights/${insightId}/`, {
        refresh: 'force_cache',
      })) as FetchedInsight;
      rows.push(...insightReportRows(insight, asOf));
    }
    if (rows.length === 0) {
      rows.push({
        metric: dashboard.name,
        thisWeek: null,
        lastWeek: null,
        weeks: [],
        unavailable: 'no insight tiles on this dashboard',
      });
    }
    sections.push({ name: dashboard.name, rows });
  }
  const date = asOf.toISOString().slice(0, 10);
  return { markdown: renderReport(sections, date), date };
}

async function nextOutputPath(
  directory: string,
  date: string,
): Promise<string> {
  for (let suffix = 1; ; suffix += 1) {
    const candidate = join(
      directory,
      `${date}-weekly${suffix === 1 ? '' : `-${suffix}`}.md`,
    );
    try {
      await access(candidate);
    } catch {
      return candidate;
    }
  }
}

async function main(): Promise<number> {
  try {
    const report = await generateReport();
    const directory = resolve(
      dirname(fileURLToPath(import.meta.url)),
      '..',
      '..',
      'docs',
      'growth',
      'reports',
    );
    await mkdir(directory, { recursive: true });
    const path = await nextOutputPath(directory, report.date);
    await writeFile(path, report.markdown, 'utf8');
    console.log(`Wrote ${path}`);
    return 0;
  } catch (err) {
    console.error(
      `Report generation failed: ${err instanceof Error ? err.message : String(err)}`,
    );
    return 1;
  }
}

const entry = process.argv[1];
if (entry && pathToFileURL(resolve(entry)).href === import.meta.url) {
  main().then((code) => process.exit(code));
}
