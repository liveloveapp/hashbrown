import { readdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { type AGUIEvent, EventType, type RunAgentInput } from '@ag-ui/core';
import { expect, test } from '@playwright/test';
import { createAppDriver } from '../harness/app-driver';
import { startIndependentEndpoint } from '../harness/independent-endpoint';

const corpus = resolve(
  __dirname,
  '../../../packages/core/src/models/fixtures/agent-frameworks',
);

/** Bind only run envelopes to the request; retain producer call/message identities and payloads. */
function bindRun(events: AGUIEvent[], input: RunAgentInput): AGUIEvent[] {
  return events.map((event) =>
    event.type === EventType.RUN_STARTED ||
    event.type === EventType.RUN_FINISHED
      ? { ...event, threadId: input.threadId, runId: input.runId }
      : event,
  );
}

/** Supply a small application-tool control response independent of framework traces. */
function answer(input: RunAgentInput): AGUIEvent[] {
  return [
    {
      type: EventType.RUN_STARTED,
      threadId: input.threadId,
      runId: input.runId,
    },
    {
      type: EventType.TEXT_MESSAGE_START,
      messageId: 'control-answer',
      role: 'assistant',
    },
    {
      type: EventType.TEXT_MESSAGE_CONTENT,
      messageId: 'control-answer',
      delta: 'Ready',
    },
    { type: EventType.TEXT_MESSAGE_END, messageId: 'control-answer' },
    {
      type: EventType.RUN_FINISHED,
      threadId: input.threadId,
      runId: input.runId,
    },
  ];
}

test('plain hosts expose neutral server-call and activity observations', async ({
  page,
}) => {
  const endpoint = await startIndependentEndpoint({ events: answer });

  try {
    await page.goto(
      `/?${new URLSearchParams({ runUrl: endpoint.url, scenario: 'tool', retries: '0' })}`,
    );
    await expect(page.getByTestId('server-tool-calls')).toHaveText('[]');
    await expect(page.getByTestId('activity-messages')).toHaveText('[]');
  } finally {
    await page.goto('about:blank');
    await endpoint.stop();
  }
});

// The corpus is generated by real producer execution, never authored in this browser spec.
for (const filename of readdirSync(corpus)
  .filter((name) => name.endsWith('.json'))
  .sort()) {
  const fixture = JSON.parse(
    readFileSync(resolve(corpus, filename), 'utf8'),
  ) as {
    framework: string;
    profile: string;
    events: AGUIEvent[];
    expected: {
      calls: {
        name: string;
        args: unknown;
        result?: string;
        resultText?: string;
      }[];
      text: string;
      activities?: { activityType: string; content: Record<string, unknown> }[];
    };
  };

  const clientProfiles = fixture.expected.calls.every(
    (call) => call.name === 'getWeather',
  )
    ? [false, true]
    : [false];
  for (const sameNameClient of clientProfiles) {
    test(`${fixture.framework} ${fixture.profile} ${fixture.expected.activities?.length ? (sameNameClient ? 'displays activity without invoking its same-name browser tool' : 'displays background activity') : sameNameClient ? 'does not rerun a completed same-name client call' : 'displays undeclared server calls'}`, async ({
      page,
    }) => {
      const endpoint = await startIndependentEndpoint({
        events: (input) => bindRun(fixture.events, input),
      });
      const driver = createAppDriver(page);

      try {
        await page.goto(
          `/?${new URLSearchParams({ runUrl: endpoint.url, scenario: sameNameClient ? 'tool' : 'plain', retries: '0' })}`,
        );
        await driver.send('What is the weather in Paris?');
        await expect(driver.assistant()).toHaveText(fixture.expected.text);
        await driver.expectIdle();
        const observed = JSON.parse(
          await page.getByTestId('server-tool-calls').innerText(),
        ) as { name: string; args: unknown; result: unknown; status: string }[];

        const expectedCalls = sameNameClient ? [] : fixture.expected.calls;
        expect(observed.map(({ name, args }) => ({ name, args }))).toEqual(
          expectedCalls.map(({ name, args }) => ({ name, args })),
        );
        expect(observed.map((call) => call.status)).toEqual(
          expectedCalls.map(() => 'complete'),
        );
        expect(observed.map((call) => call.result)).toEqual(
          expectedCalls.map((call, index) => ({
            status: 'fulfilled',
            value: fixture.events.filter(
              (event) => event.type === EventType.TOOL_CALL_RESULT,
            )[index]?.content,
          })),
        );
        const activities = JSON.parse(
          await page.getByTestId('activity-messages').innerText(),
        ) as {
          id: string;
          activityType: string;
          content: Record<string, unknown>;
        }[];
        expect(activities).toHaveLength(
          fixture.expected.activities?.length ?? 0,
        );
        for (const [index, expected] of (
          fixture.expected.activities ?? []
        ).entries()) {
          const activity = activities[index];
          expect(activity.activityType).toBe(expected.activityType);
          expect(activity.content).toMatchObject(expected.content);
          expect(activity.content['taskId']).toBe(activity.id);
          for (const field of ['startedAt', 'completedAt']) {
            const patch = fixture.events
              .flatMap((event) =>
                event.type === EventType.ACTIVITY_DELTA &&
                event.messageId === activity.id
                  ? event.patch
                  : [],
              )
              .find(
                (patch) => patch.op === 'add' && patch.path === `/${field}`,
              );
            expect(patch).toBeDefined();
            expect(activity.content[field]).toBe(
              patch && 'value' in patch ? patch.value : undefined,
            );
          }
        }
        await expect(page.getByTestId('subagents')).toHaveAttribute(
          'data-supported',
          'true',
        );
        await expect(page.getByTestId('subagents')).toHaveText('[]');
        expect(
          observed.every((call) => !Object.hasOwn(call, 'subagentRunId')),
        ).toBe(true);
        await expect(driver.toolCount()).toHaveText('0');
        await expect(driver.error()).toBeEmpty();
        await expect(driver.generatingError()).toBeEmpty();
        expect(endpoint.inputs).toHaveLength(1);
      } finally {
        await page.goto('about:blank');
        await endpoint.stop();
      }
    });
  }
}

test('ordinary application tools still execute once beside framework server-call coverage', async ({
  page,
}) => {
  const endpoint = await startIndependentEndpoint({
    events: (input) =>
      input.messages.some((message) => message.role === 'tool')
        ? answer(input)
        : [
            {
              type: EventType.RUN_STARTED,
              threadId: input.threadId,
              runId: input.runId,
            },
            {
              type: EventType.TOOL_CALL_START,
              toolCallId: 'client-weather',
              toolCallName: 'getWeather',
              parentMessageId: 'client-owner',
            },
            {
              type: EventType.TOOL_CALL_ARGS,
              toolCallId: 'client-weather',
              delta: '{"city":"Paris"}',
            },
            { type: EventType.TOOL_CALL_END, toolCallId: 'client-weather' },
            {
              type: EventType.RUN_FINISHED,
              threadId: input.threadId,
              runId: input.runId,
            },
          ],
  });
  const driver = createAppDriver(page);

  try {
    await page.goto(
      `/?${new URLSearchParams({ runUrl: endpoint.url, scenario: 'tool', retries: '0' })}`,
    );
    await driver.send('Use my browser tool.');
    await expect(driver.assistant()).toHaveText('Ready');
    await driver.expectIdle();

    await expect(driver.toolCount()).toHaveText('1');
    await expect(page.getByTestId('server-tool-calls')).toHaveText('[]');
    expect(endpoint.inputs).toHaveLength(2);
  } finally {
    await page.goto('about:blank');
    await endpoint.stop();
  }
});
