import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertValidatedInventory, loadInventory } from './inventory.mjs';

import {
  repository,
  escape,
  code,
  table,
  qualifiedProfile,
} from './report-markdown.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');

/**
 * Render a complete SDK documentation page from an unchanged validated inventory.
 * Uses only reviewed inventory values; no framework imports, clocks or network access.
 * @param inventory - The value returned by loadInventory or validateInventory.
 * @param sdk - The documentation view: react or angular.
 * @returns Deterministic Markdown with SDK-specific frontmatter and shared evidence.
 */
export function renderCompatibility(inventory, sdk) {
  assertValidatedInventory(inventory);
  assert.ok(['react', 'angular'].includes(sdk), 'Unknown documentation SDK');
  const name = sdk === 'react' ? 'React' : 'Angular';
  const qualified = inventory.profiles.filter(
    (profile) => profile.qualification,
  );
  const planned = inventory.profiles.filter(
    (profile) => !profile.qualification,
  );
  return [
    '---',
    `title: 'Framework compatibility: Hashbrown ${name} Docs'`,
    'meta:',
    '  - name: description',
    "    content: 'Versioned framework compatibility, retained evidence and planned conformance coverage.'",
    '---',
    '',
    '<!-- Generated by tools/conformance/agent-frameworks/program/report.mjs --write. -->',
    '',
    '# Framework compatibility',
    '',
    'Choose a specific framework, bridge and configuration. These are partial, versioned qualifications at the AG-UI boundary. A passing capability applies only to its named scenario and evidence stages.',
    '',
    `The seven legacy Node profiles import historical [#844](${repository}/pull/844) proof; their dates describe that retained qualification, not a new execution. Additional profiles record their own execution identity and source commit; local retained evidence does not establish CI acceptance. React and Angular share this evidence inventory; their display capabilities are recorded separately. Canonical consumer restore does not establish browser reload, reconnect or durable backend restart.`,
    '',
    '## Recorded run health',
    '',
    `Static as-of snapshot of the reviewed qualification record, not a real-time status. Status: ${code(inventory.runHealth.status)}. ${escape(inventory.runHealth.reason ?? 'No reason recorded.')}`,
    '',
    `The [weekly baseline workflow](${repository}/blob/main/.github/workflows/framework-compatibility.yml) is configured to run on main after the workflow is enabled, covering the seven approved pinned Node profiles. Candidate execution for broader Node dependency/runtime constraints has not run and requires approval. Weekly attempts do not rewrite reviewed last qualified claims. This page does not claim a new weekly run exists or passed.`,
    '',
    'A separate pinned Python baseline is configured for the isolated Pydantic AI host, prepared-store consumer, and live React and Angular browser gates. Its identical pinned candidate is deduplicated rather than executed as a second version combination. Broader Python dependency or runtime candidates require reviewed approval. These configured jobs do not establish a fresh execution or change last qualified claims.',
    '',
    '## Reading the states',
    '',
    table(
      ['State', 'Meaning'],
      [
        [
          'passed',
          'Required scenario stages passed for this exact configuration.',
        ],
        [
          'recipe-required',
          'Native enrichment gap; does not mean a recipe was tested. An executed recipe needs its own versioned profile and evidence.',
        ],
        [
          'missing-upstream',
          'Retained execution demonstrates a producer or bridge gap.',
        ],
        [
          'unsupported',
          'Authoritatively absent capability; a failed probe alone is insufficient.',
        ],
        [
          'not-tested',
          'No sufficient execution evidence; includes all planned coverage.',
        ],
        ['deferred', 'Intentionally outside this delivery.'],
      ],
    ),
    '',
    '## Capability families',
    '',
    'The catalog describes coverage targets. Inclusion does not qualify a profile for the whole family.',
    '',
    table(
      ['Family', 'Stable ID'],
      inventory.catalog.families.map((family) => [
        escape(family.label),
        code(family.id),
      ]),
    ),
    '',
    '## Last qualified profiles',
    '',
    ...qualified.map(qualifiedProfile),
    '## Retained producer gaps',
    '',
    ...inventory.producerGaps.flatMap((gap) => [
      `### ${escape(gap.framework)}: ${escape(gap.capability)}`,
      '',
      `State: ${code(gap.status)}. ${escape(gap.detail)}`,
      '',
    ]),
    '## Planned profiles: not-tested',
    '',
    'Listing a candidate is neither a compatibility claim nor a dependency approval. All scenarios linked below remain not-tested for each planned profile.',
    '',
    ...planned.flatMap((profile) => [
      `### ${escape(profile.label ?? profile.framework)}`,
      '',
      `Profile: ${code(profile.id)}. State: ${code(profile.status)}. Kind: ${code(profile.kind)}.`,
      '',
      escape(profile.detail),
      '',
      profile.scenarioIds.length === inventory.catalog.scenarios.length &&
      inventory.catalog.scenarios.every((scenario) =>
        profile.scenarioIds.includes(scenario.id),
      )
        ? `Scenario scope: all ${profile.scenarioIds.length} scenarios in the shared catalog below.`
        : `Scenario IDs: ${profile.scenarioIds.map(code).join(', ')}.`,
      '',
    ]),
    '## Microsoft Agent Framework (.NET) audit boundary',
    '',
    `Display qualification: ${code(inventory.existingDotnetHost.status)}. ${escape(inventory.existingDotnetHost.scope)}`,
    '',
    'This source audit does not establish executed display qualification. The maintained native history/recovery suites remain a separate evidence set.',
    '',
    '## Scenario catalog',
    '',
    ...inventory.catalog.families.flatMap((family) => [
      `### ${escape(family.label)}`,
      '',
      ...inventory.catalog.scenarios
        .filter((scenario) => scenario.family === family.id)
        .flatMap((scenario) => [
          `#### ${escape(scenario.id)}`,
          '',
          escape(scenario.expectation),
          '',
          `Required stages: ${scenario.requiredStages.map(code).join(', ')}.`,
          '',
        ]),
    ]),
    '## Deferred and reproduction',
    '',
    ...inventory.deferred.map((item) => `- ${code(item)}: deferred.`),
    '',
    `The [reviewed registry](${repository}/tree/main/tools/conformance/agent-frameworks/program) contains the catalog and qualification records. Producer captures and assertion sources above link to the immutable qualification commit, with retained SHA-256 hashes. New registry files are not claimed to exist at that historical commit.`,
    '',
    'Validate and reproduce the checked-in projection without installing frameworks:',
    '',
    '```sh',
    'node --test tools/conformance/agent-frameworks/program/*.spec.mjs',
    'node tools/conformance/agent-frameworks/program/report.mjs --check',
    '```',
    '',
    'Capture regeneration and qualification promotion require an explicit reviewed change. Durable checked-in captures and source assertions support these records; this page does not rely solely on expiring CI artifacts.',
    '',
  ].join('\n');
}

/**
 * Write or check both generated pages using the repository's validated inventory.
 * @param outputRoot - Root containing the destination www directory; may be a temporary directory.
 * @param options - Explicit write or check mode. Inventory always loads from this repository.
 * @returns The two generated destination paths.
 */
export async function generateCompatibility(outputRoot = root, { mode } = {}) {
  assert.ok(['write', 'check'].includes(mode), 'Expected mode write or check');
  const inventory = await loadInventory();
  const destinations = [];
  for (const sdk of ['react', 'angular']) {
    const path = resolve(
      outputRoot,
      `www/content/docs/${sdk}/platform/compatibility.md`,
    );
    const page = renderCompatibility(inventory, sdk);
    if (mode === 'write') {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, page);
    } else {
      const current = await readFile(path, 'utf8').catch((error) => {
        if (error.code === 'ENOENT')
          throw new Error(`Missing generated page: ${path}`);
        throw error;
      });
      assert.equal(
        current,
        page,
        `Stale generated page: ${path}; run report.mjs --write`,
      );
    }
    destinations.push(path);
  }
  return destinations;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  const mode = args.shift();
  const outputRoot = args.length === 2 && args[0] === '--root' ? args[1] : root;
  assert.ok(
    ['--write', '--check'].includes(mode) &&
      (args.length === 0 || (args.length === 2 && args[0] === '--root')),
    'Usage: report.mjs <--write|--check> [--root output-directory]',
  );
  await generateCompatibility(outputRoot, { mode: mode.slice(2) });
}
